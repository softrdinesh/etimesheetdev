    /// <summary>
    /// Optional. The most hours a day this assignment may log. Not negative,
    /// and 24 or fewer. Left out means this assignment sets no cap.
    /// <para>
    /// <b>Stored only.</b> No endpoint enforces it: the daily cap the time log
