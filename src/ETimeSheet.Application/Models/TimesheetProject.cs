/// <summary>
/// Body of <c>add-edit-timesheet-project</c> - <b>one payload for both add and
/// edit</b>.
/// <para>
/// <see cref="ProjectId"/> decides which: absent or <c>0</c> adds a new project
/// to <see cref="OrganizationId"/>; anything greater updates that project,
/// which must belong to <see cref="OrganizationId"/>.
/// </para>
/// <para>
/// An edit overwrites every field with what is sent - a field left out is
/// saved as null, not left as it was.
/// </para>
/// <para>
/// There is no code here: the database generates it on add - PR0001, PR0002
/// ... - and an edit never changes it.
/// </para>
/// <para>
/// There is no currency either: it is taken from <see cref="ClientId"/> - the
/// client's <c>Currencycode</c> - so changing the client changes it too.
/// </para>
/// <para>
/// Validated by <c>TimesheetProjectService</c>, not by a FluentValidation
/// validator.
/// </para>
/// </summary>
public class TimesheetProjectSaveRequest
{
    /// <summary>Absent or <c>0</c> to add; the id of a project in this organisation to update it.</summary>
    /// <example>0</example>
    public int? ProjectId { get; set; }

    /// <summary>The organisation the project belongs to. Required, greater than 0.</summary>
    /// <example>12</example>
    public int OrganizationId { get; set; }

    /// <summary>Optional, at most 100 characters. Leading and trailing spaces are trimmed.</summary>
    /// <example>Website redesign</example>
    public string? ProjectName { get; set; }

    /// <summary>Optional. Not negative; at most two decimal places are stored.</summary>
    /// <example>25000.00</example>
    public decimal? TotalBudget { get; set; }

    /// <summary>
    /// Optional. Hours as a number, not <c>hh:mm:ss</c> - <c>37.5</c> is 37½
    /// hours - and may exceed 24. Not negative; at most two decimal places are
    /// stored. The same as the budget's <c>AllocatedHours</c>.
    /// </summary>
    /// <example>120.5</example>
    public decimal? TotalHours { get; set; }

    /// <summary>Optional.</summary>
    /// <example>2026-10-01T00:00:00</example>
    public DateTime? StartDate { get; set; }

    /// <summary>Optional. Not before <see cref="StartDate"/> when both are sent.</summary>
    /// <example>2026-12-31T00:00:00</example>
    public DateTime? EndDate { get; set; }

    /// <summary>
    /// Optional. A <c>dbo.TimesheetProjectStatus.StatusID</c> of the
    /// organisation. Greater than 0 when sent.
    /// </summary>
    /// <example>1</example>
    public int? Status { get; set; }

    /// <summary>
    /// The client the project is for. Required, greater than 0, and must be a
    /// live (not deleted) client. An update can change it.
    /// </summary>
    /// <example>5</example>
    public int ClientId { get; set; }

    /// <summary>
    /// Optional. How often the project's timesheets are submitted: <c>1</c>
    /// weekly, <c>2</c> every 15 days, <c>3</c> monthly. Left out, it is saved
    /// as null - on an update too.
    /// </summary>
    /// <example>1</example>
    public int? SubmissionFrequency { get; set; }
}

