/*
    THE TIMESHEET PROJECT MODULE'S MODEL - one file, every shape the module
    exchanges.

    TimesheetProjectController and TimesheetProjectService have exactly one
    model file between them, and this is it: the request payloads, the
    response payloads, and the rows the module's stored procedures return.
    Adding a shape to this module means adding a class HERE, not adding a file
    next to it.

    Not here, deliberately:
      - The EF entity (Models/Entities/TimesheetProject.cs) maps one-to-one to
        a TABLE, not to a controller.
      - Mappings and services keep their own files; this is the model, not the
        module.

    ORDER MATTERS in the response types. System.Text.Json writes properties in
    declaration order, so moving a property up or down here changes the JSON a
    client receives. Reordering is a contract change, not a tidy-up.
*/

namespace ETimeSheet.Application.Models;

/// <summary>
/// One project from <c>dbo.TimesheetProject</c>, as
/// <c>get-timesheet-project-by-orgID</c> and
/// <c>add-edit-timesheet-project</c> return it.
/// </summary>
public class TimesheetProjectResponse
{
    public int ProjectId { get; set; }

    /// <summary>Generated by the database on add - PR0001, PR0002 ... - and never changed.</summary>
    public string? Code { get; set; }

    /// <summary>The <c>Projectname</c> column. Nullable on the table.</summary>
    public string? ProjectName { get; set; }

    public decimal? TotalBudget { get; set; }

    /// <summary>The <c>Totalhours</c> column - a number of hours, which may exceed 24.</summary>
    public decimal? TotalHours { get; set; }

    public DateTime? StartDate { get; set; }

    public DateTime? EndDate { get; set; }

    public int? CurrencyCode { get; set; }

    /// <summary>A <c>dbo.TimesheetProjectStatus.StatusID</c>.</summary>
    public int? Status { get; set; }

    /// <summary>
    /// The status's name from <c>dbo.TimesheetProjectStatus</c> - Open, Closed,
    /// Pending. Null when <see cref="Status"/> is null or names no status.
    /// </summary>
    public string? StatusName { get; set; }
}

/// <summary>
/// One row of <c>dbo.spc_GetTimesheetProject</c> - a project of one
