/// <summary>
/// Body of <c>add-edit-timesheet-project-budget</c> - <b>one payload for both
/// add and edit</b>.
/// <para>
/// A project has exactly one budget, so there is no budget id here:
/// <see cref="ProjectId"/> decides. A project that has a budget gets it
/// updated; a project that has none gets one added.
/// </para>
/// <para>
/// An update overwrites every field with what is sent - a field left out is
/// saved as null, not left as it was. There is no amount here: it is worked
/// out as <see cref="AllocatedHours"/> x <see cref="HourlyRate"/>.
/// </para>
/// <para>
/// Validated by <c>TimesheetProjectService</c>, not by a FluentValidation
/// validator.
/// </para>
/// </summary>
public class TimesheetProjectBudgetSaveRequest
{
    /// <summary>
    /// The project whose budget to save. Required, greater than 0, and must
    /// exist. It decides add or update.
    /// </summary>
    /// <example>5</example>
    public int ProjectId { get; set; }

    /// <summary>
    /// Optional. When sent, a live project category of the project's
    /// organisation.
    /// </summary>
    /// <example>3</example>
    public int? ProjectCategoryId { get; set; }

    /// <summary>Optional. Hours as a number, not <c>hh:mm:ss</c>. Not negative.</summary>
    /// <example>120.5</example>
    public decimal? AllocatedHours { get; set; }

    /// <summary>Optional. Not negative.</summary>
    /// <example>45.00</example>
    public decimal? HourlyRate { get; set; }

    /// <summary>Optional. Only the date is stored.</summary>
    /// <example>2026-10-01</example>
    public DateTime? PeriodStart { get; set; }

    /// <summary>Optional. Only the date is stored. Not before <see cref="PeriodStart"/> when both are sent.</summary>
    /// <example>2026-12-31</example>
    public DateTime? PeriodEnd { get; set; }
}

