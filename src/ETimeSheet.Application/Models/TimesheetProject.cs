/// <summary>
/// Body of <c>remove-timesheet-project</c>.
/// <para>
/// A <b>hard</b> delete: <c>dbo.TimesheetProject</c> has no soft-delete or
/// audit columns, so the row is physically removed and nothing records who
/// removed it. The project's budget in <c>dbo.TimesheetProjectBudget</c> is
/// removed with it.
/// </para>
/// <para>
/// Validated by <c>TimesheetProjectService</c>, not by a FluentValidation
/// validator.
/// </para>
/// </summary>
public class TimesheetProjectDeleteRequest
{
    /// <summary>The project to remove. Required, greater than 0.</summary>
    /// <example>3</example>
    public int ProjectId { get; set; }

    /// <summary>
    /// The organisation the project must belong to. Required, greater than 0.
    /// A project of another organisation is a 404, never removed.
    /// </summary>
    /// <example>12</example>
    public int OrganizationId { get; set; }
}

