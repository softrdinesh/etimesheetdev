/*
    Table: dbo.TimesheetProject
    Recorded: 2026-10-13 (sp_help column list supplied by the database owner,
              who created the table by hand; ProjectID is IDENTITY(1,1) as
              stated by the owner)
    Revised:  2026-10-13 - Status linked to the new lookup
              dbo.TimesheetProjectStatus (presumed; no foreign key).
    Revised:  2026-10-13 - by the owner: Totalhours changed from time(7) to
              decimal(18,2), a number of hours, so a project can be budgeted
              more than 24 hours.
    Revised:  2026-10-14 - by the owner: ClientID int NOT NULL added, the
              client the project is for.
    Revised:  2026-10-16 - DRAFT, requested by the owner, NOT YET APPLIED:
              SubmissionFrequency int NULL added, with
              CK_TimesheetProject_SubmissionFrequency limiting it to 1, 2 or 3.
              Change to applied once the owner has run it.

    One row per project: its code and name, budget in money and in hours,
    start and end dates, currency, organization, status, client and how often
    its timesheets are submitted.

    Mapped by:
      src/ETimeSheet.Application/Models/Entities/TimesheetProject.cs
      src/ETimeSheet.Infrastructure/Data/Configurations/TimesheetProjectConfiguration.cs
      (for the hard delete in POST api/v1/TimesheetProject/remove-timesheet-project)

    Read by:
      ../procedures/dbo.spc_GetTimesheetProject.sql
      (TimesheetProjectRepository, for GET api/v1/TimesheetProject/get-timesheet-project-by-orgID/{orgID})
      ../procedures/dbo.spc_GetTimesheetProjectBudgetByOrgID.sql
      (TimesheetProjectRepository, for GET api/v1/TimesheetProject/get-timesheet-project-budget-by-orgID/{orgID})

    Written by:
      ../procedures/dbo.spc_AddEditTimesheetProject.sql
      (TimesheetProjectRepository, for POST api/v1/TimesheetProject/add-edit-timesheet-project)

    Column quirks worth knowing:
      - ProjectID is IDENTITY(1,1): the database assigns it on insert.
      - Column names are irregularly cased: Projectname and Totalhours
        (lower-case "name" / "hours"), alongside TotalBudget, StartDate,
        CurrencyCode. Map each one by its exact name.
      - ProjectID, Code and ClientID are NOT NULL. Everything else is nullable.
      - Code is generated by spc_AddEditTimesheetProject on add - PR0001,
        PR0002 ..., one sequence across every organisation - and never
        changed. No unique constraint was reported.
      - TotalBudget is decimal(18,2).
      - Totalhours is decimal(18,2) - a number of hours (37.5 is 37 1/2
        hours), the same as dbo.TimesheetProjectBudget.AllocatedHours. It was
        time(7) until 2026-10-13, which capped it at 23:59:59.
      - StartDate and EndDate are plain datetime - local or UTC is not stated.
      - CurrencyCode is an int, so presumably dbo.CountryCurrency.CurrencyID
        (as Currencycode is on dbo.Timesheetclientsetup), not an ISO code.
        No foreign key was reported.
      - OrganizationID is presumably dbo.Organization's id; no foreign key
        was reported.
      - Status is presumably a dbo.TimesheetProjectStatus.StatusID
        (1 Open, 2 Closed, 3 Pending); no foreign key was reported.
      - ClientID is a dbo.TimesheetClientSetup.ClientID. No foreign key was
        reported; the API checks the client exists and is not deleted before
        saving. Recorded as the last column, where ALTER TABLE ... ADD puts
        it. No default was reported.
      - SubmissionFrequency is how often the project's timesheets are
        submitted: 1 = weekly, 2 = every 15 days, 3 = monthly. A CHECK
        constraint allows only those three; NULL is allowed, so projects
        that existed before the column was added keep NULL until they are
        given one. No default. Read by spc_GetTimesheetProject and written
        by spc_AddEditTimesheetProject.

    STILL UNCONFIRMED:
      - Whether ProjectID is the primary key. It is IDENTITY(1,1), but no key
        was reported, so none is recorded below.
      - Defaults, constraints and indexes - none were supplied.
      - That Status holds a dbo.TimesheetProjectStatus.StatusID.

    Lengths below are characters. sp_help reports nvarchar lengths in BYTES, so
    the 40 / 200 it prints for Code / Projectname are 20 / 100 characters.
*/

IF OBJECT_ID(N'dbo.TimesheetProject', N'U') IS NOT NULL
    DROP TABLE dbo.TimesheetProject;
GO

CREATE TABLE dbo.TimesheetProject
(
    ProjectID       int             IDENTITY(1,1) NOT NULL,
    Code            nvarchar(20)    NOT NULL,
    Projectname     nvarchar(100)   NULL,
    TotalBudget     decimal(18,2)   NULL,
    Totalhours      decimal(18,2)   NULL,
    StartDate       datetime        NULL,
    EndDate         datetime        NULL,
    CurrencyCode    int             NULL,
    OrganizationID  int             NULL,
    Status          int             NULL,
    ClientID        int             NOT NULL,
    SubmissionFrequency int         NULL,
    CONSTRAINT CK_TimesheetProject_SubmissionFrequency
        CHECK (SubmissionFrequency IN (1, 2, 3))
);
GO
